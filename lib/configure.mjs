// Cross-platform deployment, using only Node built-ins. No package installation here.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const [agent, ...args] = process.argv.slice(2);
if (!['claude', 'codex', 'opencode'].includes(agent)) throw new Error('Expected agent name');
const options = {};
for (let i = 0; i < args.length; i += 2) {
  if (!['--bin', '--profile'].includes(args[i]) || args[i + 1] === undefined) throw new Error('Invalid configure arguments');
  options[args[i]] = args[i + 1];
}
const home = os.homedir();
const env = process.env;
const destination = path.resolve(agent === 'claude' ? (env.CLAUDE_CONFIG_DIR || path.join(home, '.claude'))
  : agent === 'codex' ? (env.CODEX_HOME || path.join(home, '.codex'))
    : (env.OPENCODE_CONFIG_DIR || path.join(env.XDG_CONFIG_HOME || path.join(home, '.config'), 'opencode')));
const sh = value => `'${value.replaceAll("'", "'\\''")}'`;
const ps = value => `'${value.replaceAll("'", "''")}'`;
function read(file) {
  const bytes = fs.readFileSync(file);
  // Windows PowerShell 5.1 commonly writes profiles as UTF-16LE with a BOM.
  if (bytes[0] === 0xff && bytes[1] === 0xfe) return bytes.subarray(2).toString('utf16le');
  if (bytes[0] === 0xfe && bytes[1] === 0xff) return Buffer.from(bytes.subarray(2)).swap16().toString('utf16le');
  // Fail rather than silently corrupt a profile in an unknown legacy encoding.
  return new TextDecoder('utf-8', { fatal: true }).decode(bytes);
}
const source = file => path.join(root, agent, file);

function write(file, content) {
  // PS5 interprets BOM-less scripts as ANSI, so generated Unicode paths need a BOM.
  const bytes = Buffer.from((file.toLowerCase().endsWith('.ps1') ? '\ufeff' : '') + content, 'utf8');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  let existing;
  try { existing = fs.lstatSync(file); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (existing) {
    // Never replace a symlinked config/profile: its actual ownership is ambiguous.
    if (existing.isSymbolicLink()) throw new Error(`Refusing to replace symlink: ${file}`);
    if (fs.readFileSync(file).equals(bytes)) return;
    const backup = `${file}.bak.${Date.now()}.${randomUUID()}`;
    fs.copyFileSync(file, backup, fs.constants.COPYFILE_EXCL);
    fs.chmodSync(backup, 0o600);
    console.log(`Backup: ${backup}`);
  }
  const temp = `${file}.tmp.${randomUUID()}`;
  try {
    fs.writeFileSync(temp, bytes, { mode: 0o600, flag: 'wx' });
    fs.renameSync(temp, file);
  } finally {
    if (fs.existsSync(temp)) fs.unlinkSync(temp);
  }
  console.log(`Configured: ${file}`);
}
function json(file, data) { write(file, JSON.stringify(data, null, 2) + '\n'); }
function asset(file) { write(path.join(destination, file), read(source(file))); }

if (agent === 'claude') {
  const config = JSON.parse(read(source('settings.json')));
  const status = path.join(destination, 'statusline.mjs');
  // Windows Claude invokes command strings through a shell; forward slashes work in Git Bash too.
  const quote = process.platform === 'win32' ? value => `"${value.replaceAll('\\', '/')}"` : sh;
  config.statusLine = { type: 'command', command: `${quote(process.execPath)} ${quote(status)}` };
  asset('statusline.mjs');
  json(path.join(destination, 'settings.json'), config);
} else if (agent === 'codex') {
  // TOML basic strings and JSON strings share escaping for ordinary filesystem paths.
  const logPath = path.join(destination, 'log');
  write(path.join(destination, 'config.toml'), `log_dir = ${JSON.stringify(logPath)}\n\n${read(source('config.toml'))}`);
} else {
  const config = JSON.parse(read(source('opencode.json')));
  config.instructions = [path.join(destination, 'attribution.md').replaceAll('\\', '/')];
  asset('attribution.md');
  json(path.resolve(env.OPENCODE_CONFIG || path.join(destination, 'opencode.json')), config);
  asset('cli.json');
}

// Keep PATH separately so --config-only does not erase a previously installed npm prefix.
const bin = options['--bin'];
if (bin) {
  write(path.join(destination, 'path.sh'), `export PATH=${sh(bin)}:"$PATH"\n`);
  write(path.join(destination, 'path.ps1'), `$env:PATH = ${ps(bin)} + [IO.Path]::PathSeparator + $env:PATH\n`);
}
const nodeBin = path.dirname(process.execPath);
let shell = `# Generated by agentenv; source in shells and container entrypoints.\nexport PATH=${sh(nodeBin)}:"$PATH"\n`;
let powershell = `# Generated by agentenv; dot-source before starting agents.\n$env:PATH = ${ps(nodeBin)} + [IO.Path]::PathSeparator + $env:PATH\n`;
if (env.AGENTENV_TOOL_PATH) {
  write(path.join(destination, 'tools-path.sh'), `export PATH=${sh(env.AGENTENV_TOOL_PATH)}:"$PATH"\n`);
  write(path.join(destination, 'tools-path.ps1'), `$env:PATH = ${ps(env.AGENTENV_TOOL_PATH)} + [IO.Path]::PathSeparator + $env:PATH\n`);
}
shell += `[ ! -f ${sh(path.join(destination,'tools-path.sh'))} ] || . ${sh(path.join(destination,'tools-path.sh'))}\n`;
powershell += `if (Test-Path -LiteralPath ${ps(path.join(destination,'tools-path.ps1'))}) { . ${ps(path.join(destination,'tools-path.ps1'))} }\n`;
const pathSh = sh(path.join(destination, 'path.sh'));
const pathPs = ps(path.join(destination, 'path.ps1'));
shell += `[ ! -f ${pathSh} ] || . ${pathSh}\n`;
powershell += `if (Test-Path -LiteralPath ${pathPs}) { . ${pathPs} }\n`;
if (agent === 'opencode') {
  shell += read(source('env.sh'));
  powershell += read(source('env.ps1'));
}
write(path.join(destination, 'env.sh'), shell);
write(path.join(destination, 'env.ps1'), powershell);

function profile(file, body) {
  const begin = `# >>> agentenv ${agent} >>>`;
  const end = `# <<< agentenv ${agent} <<<`;
  const old = fs.existsSync(file) ? read(file) : '';
  const start = old.indexOf(begin);
  let next;
  if (start === -1) next = old + (old && !old.endsWith('\n') ? '\n' : '') + `${begin}\n${body}\n${end}\n`;
  else {
    const finish = old.indexOf(end, start);
    if (finish === -1) throw new Error(`Incomplete agentenv block in ${file}`);
    next = old.slice(0, start) + `${begin}\n${body}\n${end}` + old.slice(finish + end.length);
  }
  write(file, next);
}
if (options['--profile']) {
  profile(options['--profile'], `. ${ps(path.join(destination, 'env.ps1'))}`);
} else {
  const body = `. ${sh(path.join(destination, 'env.sh'))}`;
  // bash interactive/non-login, zsh interactive, and POSIX login shells.
  for (const name of ['.bashrc', '.zshrc', '.profile']) profile(path.join(home, name), body);
  // Bash skips .profile if either of these already exists.
  for (const name of ['.bash_profile', '.bash_login']) {
    if (fs.existsSync(path.join(home, name))) { profile(path.join(home, name), body); break; }
  }
}
